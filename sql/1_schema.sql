-- =====================================================================
-- BTL2 - Hệ thống quản lý đặt phòng du lịch (tham khảo Booking.com)
-- Phần 1.1: Tạo bảng + ràng buộc khóa chính, khóa ngoại, CHECK
-- DBMS: MySQL 8.0.16+ (cần CHECK constraint, generated column, CTE)
-- Ràng buộc không viết được bằng CHECK nằm trong 2_triggers.sql
-- =====================================================================
DROP DATABASE IF EXISTS booking_db;
CREATE DATABASE booking_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE booking_db;

-- ---------------------------------------------------------------------
-- Nghiệp vụ 1: Tài khoản, khách hàng thân thiết
-- USER_TYPE (G/H/A) + khóa ngoại kép ở lớp con => chuyên biệt hóa rời nhau
-- (mỗi người dùng thuộc đúng 1 trong 3 nhóm)
-- ---------------------------------------------------------------------
CREATE TABLE `USER` (
  USER_ID        INT AUTO_INCREMENT PRIMARY KEY,
  USER_TYPE      CHAR(1)      NOT NULL,
  EMAIL          VARCHAR(100) NOT NULL UNIQUE,
  PASSWORD       VARCHAR(255) NOT NULL,
  FULL_NAME      VARCHAR(100) NOT NULL,
  PHONE_NUMBER   VARCHAR(15),
  PROFILE_IMAGE  VARCHAR(255),
  CREATED_DATE   DATE NOT NULL DEFAULT (CURRENT_DATE),
  STREET_ADDRESS VARCHAR(150),
  WARD           VARCHAR(50),
  DISTRICT       VARCHAR(50),
  CITY           VARCHAR(50),
  UNIQUE KEY UQ_USER_TYPE (USER_ID, USER_TYPE),
  CONSTRAINT CK_USER_TYPE  CHECK (USER_TYPE IN ('G', 'H', 'A')),
  CONSTRAINT CK_USER_EMAIL CHECK (EMAIL REGEXP '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$'),
  CONSTRAINT CK_USER_PHONE CHECK (PHONE_NUMBER REGEXP '^(0|\\+84)[0-9]{9}$')
);

CREATE TABLE REFER (
  REFERRED_USER_ID INT PRIMARY KEY,
  REFERRER_ID      INT NOT NULL,
  FOREIGN KEY (REFERRED_USER_ID) REFERENCES `USER` (USER_ID),
  FOREIGN KEY (REFERRER_ID)      REFERENCES `USER` (USER_ID),
  CONSTRAINT CK_REFER_SELF CHECK (REFERRED_USER_ID <> REFERRER_ID)
);

CREATE TABLE GUEST (
  USER_ID      INT PRIMARY KEY,
  USER_TYPE    CHAR(1) NOT NULL DEFAULT 'G',
  BIRTH_DATE   DATE,
  GENDER       CHAR(1),
  GENIUS_LEVEL TINYINT NOT NULL DEFAULT 1,      -- thuộc tính dẫn xuất, cập nhật bằng trigger
  FOREIGN KEY (USER_ID, USER_TYPE) REFERENCES `USER` (USER_ID, USER_TYPE),
  CONSTRAINT CK_GUEST_TYPE   CHECK (USER_TYPE = 'G'),
  CONSTRAINT CK_GUEST_GENDER CHECK (GENDER IN ('M', 'F', 'O')),
  CONSTRAINT CK_GUEST_GENIUS CHECK (GENIUS_LEVEL BETWEEN 1 AND 3)
);

CREATE TABLE HOST (
  USER_ID       INT PRIMARY KEY,
  USER_TYPE     CHAR(1) NOT NULL DEFAULT 'H',
  TAX_CODE      VARCHAR(14)  NOT NULL UNIQUE,
  BUSINESS_NAME VARCHAR(150) NOT NULL,
  BANK_ACCOUNT  VARCHAR(20)  NOT NULL,
  FOREIGN KEY (USER_ID, USER_TYPE) REFERENCES `USER` (USER_ID, USER_TYPE),
  CONSTRAINT CK_HOST_TYPE CHECK (USER_TYPE = 'H'),
  CONSTRAINT CK_HOST_TAX  CHECK (TAX_CODE REGEXP '^[0-9]{10}(-[0-9]{3})?$'),
  CONSTRAINT CK_HOST_BANK CHECK (BANK_ACCOUNT REGEXP '^[0-9]{6,20}$')
);

CREATE TABLE ADMIN (
  USER_ID    INT PRIMARY KEY,
  USER_TYPE  CHAR(1) NOT NULL DEFAULT 'A',
  ADMIN_ROLE VARCHAR(30) NOT NULL,
  FOREIGN KEY (USER_ID, USER_TYPE) REFERENCES `USER` (USER_ID, USER_TYPE),
  CONSTRAINT CK_ADMIN_TYPE CHECK (USER_TYPE = 'A'),
  CONSTRAINT CK_ADMIN_ROLE CHECK (ADMIN_ROLE IN ('SUPER_ADMIN', 'MODERATOR', 'SUPPORT', 'FINANCE', 'CONTENT'))
);

CREATE TABLE WALLET (
  USER_ID        INT PRIMARY KEY,
  BALANCE        DECIMAL(15, 2) NOT NULL DEFAULT 0,
  LOYALTY_POINTS INT NOT NULL DEFAULT 0,
  FOREIGN KEY (USER_ID) REFERENCES GUEST (USER_ID),
  CONSTRAINT CK_WALLET_BALANCE CHECK (BALANCE >= 0),
  CONSTRAINT CK_WALLET_POINTS  CHECK (LOYALTY_POINTS >= 0)
);

-- BTL1 lưu TRANSACTION_HISTORY như 1 chuỗi -> không biết số tiền/thời điểm. Sửa: tách cột.
CREATE TABLE WALLET_TRANSACTION (
  USER_ID          INT,
  TRANSACTION_TIME DATETIME,
  AMOUNT           DECIMAL(15, 2) NOT NULL,
  DESCRIPTION      VARCHAR(255)   NOT NULL,
  PRIMARY KEY (USER_ID, TRANSACTION_TIME),
  FOREIGN KEY (USER_ID) REFERENCES WALLET (USER_ID),
  CONSTRAINT CK_WTX_AMOUNT CHECK (AMOUNT <> 0)
);

CREATE TABLE COMPANION (
  USER_ID      INT,
  COMPANION_NO INT,
  FULL_NAME    VARCHAR(100) NOT NULL,
  BIRTH_DATE   DATE,
  PHONE_NUMBER VARCHAR(15),
  PRIMARY KEY (USER_ID, COMPANION_NO),
  FOREIGN KEY (USER_ID) REFERENCES GUEST (USER_ID),
  CONSTRAINT CK_COMPANION_PHONE CHECK (PHONE_NUMBER REGEXP '^(0|\\+84)[0-9]{9}$')
);

CREATE TABLE PAYMENT_CARD (
  CARD_NUMBER     VARCHAR(19) PRIMARY KEY,
  CARDHOLDER_NAME VARCHAR(100) NOT NULL,
  EXPIRY_DATE     DATE         NOT NULL,
  CARD_TYPE       VARCHAR(20)  NOT NULL,
  USER_ID         INT          NOT NULL,
  FOREIGN KEY (USER_ID) REFERENCES GUEST (USER_ID),
  CONSTRAINT CK_CARD_NUMBER CHECK (CARD_NUMBER REGEXP '^[0-9]{13,19}$'),
  CONSTRAINT CK_CARD_TYPE   CHECK (CARD_TYPE IN ('VISA', 'MASTERCARD', 'JCB', 'AMEX'))
);

CREATE TABLE VOUCHER (
  VOUCHER_CODE          VARCHAR(20) PRIMARY KEY,
  DISCOUNT_VALUE        DECIMAL(15, 2) NOT NULL,       -- số tiền giảm (VND)
  APPLICABLE_CONDITIONS VARCHAR(255),
  EXPIRY_DATE           DATE NOT NULL,
  STATUS                VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
  USER_ID               INT NOT NULL,
  FOREIGN KEY (USER_ID) REFERENCES GUEST (USER_ID),
  CONSTRAINT CK_VOUCHER_VALUE  CHECK (DISCOUNT_VALUE > 0),
  CONSTRAINT CK_VOUCHER_STATUS CHECK (STATUS IN ('ACTIVE', 'EXPIRED', 'USED'))
);

-- ---------------------------------------------------------------------
-- Nghiệp vụ 2: Cơ sở lưu trú, tiện ích, hạng phòng
-- ACC_TYPE (HOTEL/RESORT/APARTMENT/HOMESTAY): mỗi cơ sở thuộc đúng 1 loại hình
-- ---------------------------------------------------------------------
CREATE TABLE ACCOMMODATION (
  ACCOMMODATION_ID    INT AUTO_INCREMENT PRIMARY KEY,
  ACC_TYPE            VARCHAR(10)  NOT NULL,
  NAME                VARCHAR(150) NOT NULL,
  DESCRIPTION         TEXT,
  STAR_RATING         TINYINT NOT NULL,
  CHECK_IN_TIME       TIME NOT NULL DEFAULT '14:00',
  CHECK_OUT_TIME      TIME NOT NULL DEFAULT '12:00',
  CANCELLATION_POLICY VARCHAR(255),
  PET_POLICY          VARCHAR(255),
  CHILD_POLICY        VARCHAR(255),
  CONTACT_EMAIL       VARCHAR(100),
  PHONE_NUMBER        VARCHAR(15),
  STREET_ADDRESS      VARCHAR(150) NOT NULL,
  WARD                VARCHAR(50),
  DISTRICT            VARCHAR(50),
  CITY                VARCHAR(50)  NOT NULL,
  LONGITUDE           DECIMAL(9, 6),
  LATITUDE            DECIMAL(8, 6),
  USER_ID             INT NOT NULL,
  UNIQUE KEY UQ_ACC_TYPE (ACCOMMODATION_ID, ACC_TYPE),
  FOREIGN KEY (USER_ID) REFERENCES HOST (USER_ID),
  CONSTRAINT CK_ACC_TYPE  CHECK (ACC_TYPE IN ('HOTEL', 'RESORT', 'APARTMENT', 'HOMESTAY')),
  CONSTRAINT RB04_STAR    CHECK (STAR_RATING BETWEEN 1 AND 5),
  CONSTRAINT CK_ACC_EMAIL CHECK (CONTACT_EMAIL REGEXP '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$'),
  CONSTRAINT CK_ACC_PHONE CHECK (PHONE_NUMBER REGEXP '^(0|\\+84)[0-9]{9,10}$'),
  CONSTRAINT CK_ACC_COORD CHECK (LONGITUDE BETWEEN -180 AND 180 AND LATITUDE BETWEEN -90 AND 90)
);

CREATE TABLE WISHLIST (
  WISHLIST_ID      INT AUTO_INCREMENT PRIMARY KEY,
  SAVED_DATE       DATE NOT NULL DEFAULT (CURRENT_DATE),
  USER_ID          INT NOT NULL,
  ACCOMMODATION_ID INT NOT NULL,
  UNIQUE KEY UQ_WISHLIST (USER_ID, ACCOMMODATION_ID),   -- mỗi cặp khách - cơ sở chỉ 1 lần
  FOREIGN KEY (USER_ID) REFERENCES GUEST (USER_ID),
  FOREIGN KEY (ACCOMMODATION_ID) REFERENCES ACCOMMODATION (ACCOMMODATION_ID)
);

CREATE TABLE HOTEL (
  ACCOMMODATION_ID INT PRIMARY KEY,
  ACC_TYPE         VARCHAR(10) NOT NULL DEFAULT 'HOTEL',
  NUMBER_OF_FLOORS INT NOT NULL,
  FOREIGN KEY (ACCOMMODATION_ID, ACC_TYPE) REFERENCES ACCOMMODATION (ACCOMMODATION_ID, ACC_TYPE),
  CONSTRAINT CK_HOTEL_TYPE   CHECK (ACC_TYPE = 'HOTEL'),
  CONSTRAINT CK_HOTEL_FLOORS CHECK (NUMBER_OF_FLOORS >= 1)
);

CREATE TABLE HOTEL_FACILITIES (
  ACCOMMODATION_ID  INT,
  COMMON_FACILITIES VARCHAR(100),
  PRIMARY KEY (ACCOMMODATION_ID, COMMON_FACILITIES),
  FOREIGN KEY (ACCOMMODATION_ID) REFERENCES HOTEL (ACCOMMODATION_ID)
);

CREATE TABLE RESORT (
  ACCOMMODATION_ID INT PRIMARY KEY,
  ACC_TYPE         VARCHAR(10) NOT NULL DEFAULT 'RESORT',
  PROPERTY_AREA    DECIMAL(12, 2) NOT NULL,             -- m2
  FOREIGN KEY (ACCOMMODATION_ID, ACC_TYPE) REFERENCES ACCOMMODATION (ACCOMMODATION_ID, ACC_TYPE),
  CONSTRAINT CK_RESORT_TYPE CHECK (ACC_TYPE = 'RESORT'),
  CONSTRAINT CK_RESORT_AREA CHECK (PROPERTY_AREA > 0)
);

CREATE TABLE APARTMENT (
  ACCOMMODATION_ID   INT PRIMARY KEY,
  ACC_TYPE           VARCHAR(10) NOT NULL DEFAULT 'APARTMENT',
  NUMBER_OF_BEDROOMS INT NOT NULL,
  FOREIGN KEY (ACCOMMODATION_ID, ACC_TYPE) REFERENCES ACCOMMODATION (ACCOMMODATION_ID, ACC_TYPE),
  CONSTRAINT CK_APT_TYPE     CHECK (ACC_TYPE = 'APARTMENT'),
  CONSTRAINT CK_APT_BEDROOMS CHECK (NUMBER_OF_BEDROOMS >= 1)
);

CREATE TABLE HOMESTAY (
  ACCOMMODATION_ID       INT PRIMARY KEY,
  ACC_TYPE               VARCHAR(10) NOT NULL DEFAULT 'HOMESTAY',
  HOUSE_TYPE             VARCHAR(50) NOT NULL,
  NUMBER_OF_RENTAL_ROOMS INT NOT NULL,
  FOREIGN KEY (ACCOMMODATION_ID, ACC_TYPE) REFERENCES ACCOMMODATION (ACCOMMODATION_ID, ACC_TYPE),
  CONSTRAINT CK_HOMESTAY_TYPE  CHECK (ACC_TYPE = 'HOMESTAY'),
  CONSTRAINT CK_HOMESTAY_ROOMS CHECK (NUMBER_OF_RENTAL_ROOMS >= 1)
);

CREATE TABLE AMENITY (
  AMENITY_NAME  VARCHAR(100) PRIMARY KEY,
  AMENITY_GROUP VARCHAR(50) NOT NULL,
  CONSTRAINT CK_AMENITY_GROUP CHECK (AMENITY_GROUP IN ('GENERAL', 'ENTERTAINMENT', 'FOOD', 'SUPPORT'))
);

CREATE TABLE ACCOMMODATION_AMENITY (
  ACCOMMODATION_ID INT,
  AMENITY_NAME     VARCHAR(100),
  PRIMARY KEY (ACCOMMODATION_ID, AMENITY_NAME),
  FOREIGN KEY (ACCOMMODATION_ID) REFERENCES ACCOMMODATION (ACCOMMODATION_ID),
  FOREIGN KEY (AMENITY_NAME) REFERENCES AMENITY (AMENITY_NAME)
);

CREATE TABLE ROOM_TYPE (
  ACCOMMODATION_ID INT,
  ROOM_NAME        VARCHAR(50),
  AREA             DECIMAL(6, 2) NOT NULL,                -- m2
  NUMBER_OF_BEDS   TINYINT NOT NULL,
  BED_TYPE         VARCHAR(30) NOT NULL,
  ADULTS           TINYINT NOT NULL,                      -- sức chứa tối đa
  CHILDREN         TINYINT NOT NULL DEFAULT 0,
  `VIEW`           VARCHAR(50),
  PRIMARY KEY (ACCOMMODATION_ID, ROOM_NAME),
  FOREIGN KEY (ACCOMMODATION_ID) REFERENCES ACCOMMODATION (ACCOMMODATION_ID),
  CONSTRAINT CK_RT_AREA     CHECK (AREA > 0),
  CONSTRAINT CK_RT_BEDS     CHECK (NUMBER_OF_BEDS >= 1),
  CONSTRAINT CK_RT_ADULTS   CHECK (ADULTS >= 1),
  CONSTRAINT CK_RT_CHILDREN CHECK (CHILDREN >= 0)
);

CREATE TABLE ROOM_TYPE_AMENITIES (
  ACCOMMODATION_ID  INT,
  ROOM_NAME         VARCHAR(50),
  IN_ROOM_AMENITIES VARCHAR(100),
  PRIMARY KEY (ACCOMMODATION_ID, ROOM_NAME, IN_ROOM_AMENITIES),
  FOREIGN KEY (ACCOMMODATION_ID, ROOM_NAME) REFERENCES ROOM_TYPE (ACCOMMODATION_ID, ROOM_NAME)
);

CREATE TABLE ROOM (
  ACCOMMODATION_ID    INT,
  ROOM_NAME           VARCHAR(50),
  ROOM_NUMBER         VARCHAR(10),
  AVAILABILITY_STATUS VARCHAR(15) NOT NULL DEFAULT 'AVAILABLE',
  PRIMARY KEY (ACCOMMODATION_ID, ROOM_NAME, ROOM_NUMBER),
  FOREIGN KEY (ACCOMMODATION_ID, ROOM_NAME) REFERENCES ROOM_TYPE (ACCOMMODATION_ID, ROOM_NAME),
  CONSTRAINT CK_ROOM_STATUS CHECK (AVAILABILITY_STATUS IN ('AVAILABLE', 'OCCUPIED', 'MAINTENANCE'))
);

CREATE TABLE ROOM_RATE (
  ACCOMMODATION_ID   INT,
  ROOM_NAME          VARCHAR(50),
  ROOM_RATE_ID       INT,
  UNIT_PRICE         DECIMAL(15, 2) NOT NULL,             -- giá / phòng / đêm
  FREE_CANCELLATION  BOOLEAN NOT NULL DEFAULT FALSE,
  EFFECTIVE_DATE     DATE    NOT NULL,
  CHILD_PRICE        DECIMAL(15, 2) NOT NULL DEFAULT 0,
  BREAKFAST_INCLUDED BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY (ACCOMMODATION_ID, ROOM_NAME, ROOM_RATE_ID),
  FOREIGN KEY (ACCOMMODATION_ID, ROOM_NAME) REFERENCES ROOM_TYPE (ACCOMMODATION_ID, ROOM_NAME),
  CONSTRAINT CK_RATE_PRICE CHECK (UNIT_PRICE > 0 AND CHILD_PRICE >= 0)
);

