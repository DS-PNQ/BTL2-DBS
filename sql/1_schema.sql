-- ---------------------------------------------------------------------
-- Nghiệp vụ 3: Đặt phòng, thanh toán
-- ---------------------------------------------------------------------
CREATE TABLE BOOKING (
  BOOKING_ID             INT AUTO_INCREMENT PRIMARY KEY,
  STATUS                 VARCHAR(10) NOT NULL DEFAULT 'PENDING',
  ADULTS                 TINYINT NOT NULL,
  CHILDREN               TINYINT NOT NULL DEFAULT 0,
  BOOKING_CODE           VARCHAR(20) NOT NULL UNIQUE,
  PIN_CODE               CHAR(4)     NOT NULL,
  BOOKING_DATE           DATE NOT NULL DEFAULT (CURRENT_DATE),
  CHECK_IN_DATE          DATE NOT NULL,
  CHECK_OUT_DATE         DATE NOT NULL,
  ESTIMATED_ARRIVAL_TIME TIME,
  SPECIAL_REQUESTS       VARCHAR(500),
  USER_ID                INT NOT NULL,
  ACCOMMODATION_ID       INT NOT NULL,
  TOTAL_NIGHTS           INT GENERATED ALWAYS AS (DATEDIFF(CHECK_OUT_DATE, CHECK_IN_DATE)) STORED,  -- RB06
  TOTAL_AMOUNT           DECIMAL(15, 2) NOT NULL DEFAULT 0,  -- dẫn xuất, tính bằng trigger (2.2.2)
  UNIQUE KEY UQ_BOOKING_ACC (BOOKING_ID, ACCOMMODATION_ID),  -- đích của FK kép từ BOOKING_ROOM_TYPE
  FOREIGN KEY (USER_ID) REFERENCES GUEST (USER_ID),
  FOREIGN KEY (ACCOMMODATION_ID) REFERENCES ACCOMMODATION (ACCOMMODATION_ID),
  CONSTRAINT CK_BOOKING_STATUS CHECK (STATUS IN ('PENDING', 'CONFIRMED', 'COMPLETED', 'CANCELLED')),
  CONSTRAINT RB01_CHECKOUT_AFTER_CHECKIN CHECK (CHECK_OUT_DATE > CHECK_IN_DATE),
  CONSTRAINT RB02_BOOKED_BEFORE_CHECKIN  CHECK (BOOKING_DATE <= CHECK_IN_DATE),
  CONSTRAINT RB03_MIN_ONE_ADULT          CHECK (ADULTS >= 1),
  CONSTRAINT CK_BOOKING_CHILDREN         CHECK (CHILDREN >= 0),
  CONSTRAINT CK_BOOKING_PIN              CHECK (PIN_CODE REGEXP '^[0-9]{4}$'),
  CONSTRAINT CK_BOOKING_TOTAL            CHECK (TOTAL_AMOUNT >= 0)
);

-- ROOM_RATE_ID: BTL1 không ghi khách chọn gói giá nào (ăn sáng / hủy miễn phí) -> bổ sung.
-- FK kép (BOOKING_ID, ACCOMMODATION_ID): hạng phòng phải thuộc đúng cơ sở của đơn.
CREATE TABLE BOOKING_ROOM_TYPE (
  BOOKING_ID            INT,
  ACCOMMODATION_ID      INT,
  ROOM_NAME             VARCHAR(50),
  ROOM_RATE_ID          INT NOT NULL,
  ROOM_PRICE_AT_BOOKING DECIMAL(15, 2) NOT NULL,
  RESERVED_QUANTITY     TINYINT NOT NULL DEFAULT 1,
  PRIMARY KEY (BOOKING_ID, ACCOMMODATION_ID, ROOM_NAME),
  FOREIGN KEY (BOOKING_ID, ACCOMMODATION_ID) REFERENCES BOOKING (BOOKING_ID, ACCOMMODATION_ID) ON DELETE CASCADE,
  FOREIGN KEY (ACCOMMODATION_ID, ROOM_NAME) REFERENCES ROOM_TYPE (ACCOMMODATION_ID, ROOM_NAME),
  FOREIGN KEY (ACCOMMODATION_ID, ROOM_NAME, ROOM_RATE_ID) REFERENCES ROOM_RATE (ACCOMMODATION_ID, ROOM_NAME, ROOM_RATE_ID),
  CONSTRAINT CK_BRT_PRICE CHECK (ROOM_PRICE_AT_BOOKING > 0),
  CONSTRAINT CK_BRT_QTY   CHECK (RESERVED_QUANTITY >= 1)
);

-- Mỗi đơn tối đa 1 voucher (PK = BOOKING_ID), mỗi voucher dùng 1 lần (UNIQUE VOUCHER_CODE)
CREATE TABLE BOOKING_VOUCHER (
  BOOKING_ID   INT PRIMARY KEY,
  VOUCHER_CODE VARCHAR(20) NOT NULL UNIQUE,
  FOREIGN KEY (BOOKING_ID) REFERENCES BOOKING (BOOKING_ID) ON DELETE CASCADE,
  FOREIGN KEY (VOUCHER_CODE) REFERENCES VOUCHER (VOUCHER_CODE)
);

CREATE TABLE PAYMENT (
  PAYMENT_ID       INT AUTO_INCREMENT PRIMARY KEY,
  TRANSACTION_CODE VARCHAR(30) NOT NULL UNIQUE,
  CURRENCY         CHAR(3)     NOT NULL DEFAULT 'VND',
  PAYMENT_DATE     DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PAYMENT_METHOD   VARCHAR(20) NOT NULL,
  AMOUNT           DECIMAL(15, 2) NOT NULL,
  PAYMENT_STATUS   VARCHAR(12) NOT NULL DEFAULT 'PROCESSING',
  BOOKING_ID       INT NOT NULL,
  CARD_NUMBER      VARCHAR(19),
  -- 1:1 với BOOKING: mỗi đơn tối đa 1 giao dịch thành công (NULL không tính trùng)
  PAID_BOOKING_ID  INT GENERATED ALWAYS AS (IF(PAYMENT_STATUS IN ('SUCCESS', 'REFUNDED'), BOOKING_ID, NULL)) STORED UNIQUE,
  FOREIGN KEY (BOOKING_ID) REFERENCES BOOKING (BOOKING_ID),
  FOREIGN KEY (CARD_NUMBER) REFERENCES PAYMENT_CARD (CARD_NUMBER),
  CONSTRAINT CK_PAY_METHOD   CHECK (PAYMENT_METHOD IN ('CARD', 'PAY_AT_PROPERTY')),
  CONSTRAINT CK_PAY_CARD     CHECK ((PAYMENT_METHOD = 'CARD') = (CARD_NUMBER IS NOT NULL)),
  CONSTRAINT CK_PAY_STATUS   CHECK (PAYMENT_STATUS IN ('SUCCESS', 'FAILED', 'PROCESSING', 'REFUNDED')),
  CONSTRAINT CK_PAY_AMOUNT   CHECK (AMOUNT > 0),
  CONSTRAINT CK_PAY_CURRENCY CHECK (CURRENCY IN ('VND', 'USD', 'EUR'))
);

-- Thực thể yếu, 1:1 với BOOKING -> UNIQUE(BOOKING_ID)
CREATE TABLE CANCELLATION (
  BOOKING_ID        INT,
  CANCELLATION_ID   INT NOT NULL DEFAULT 1,
  CANCELLATION_DATE DATE NOT NULL DEFAULT (CURRENT_DATE),
  REASON            VARCHAR(255),
  REFUND_STATUS     VARCHAR(10) NOT NULL DEFAULT 'NONE',
  REFUND_AMOUNT     DECIMAL(15, 2) NOT NULL DEFAULT 0,
  CANCELLATION_FEE  DECIMAL(15, 2) NOT NULL DEFAULT 0,
  PRIMARY KEY (BOOKING_ID, CANCELLATION_ID),
  UNIQUE KEY UQ_CANCELLATION_BOOKING (BOOKING_ID),
  FOREIGN KEY (BOOKING_ID) REFERENCES BOOKING (BOOKING_ID) ON DELETE CASCADE,
  CONSTRAINT CK_CANCEL_REFUND_STATUS CHECK (REFUND_STATUS IN ('NONE', 'PENDING', 'REFUNDED')),
  CONSTRAINT CK_CANCEL_MONEY         CHECK (REFUND_AMOUNT >= 0 AND CANCELLATION_FEE >= 0)
);

-- ---------------------------------------------------------------------
-- Nghiệp vụ 4: Đánh giá, phản hồi, nhắn tin
-- ---------------------------------------------------------------------
CREATE TABLE REVIEW (
  REVIEW_ID        INT AUTO_INCREMENT PRIMARY KEY,
  TITLE            VARCHAR(150) NOT NULL,
  POSITIVE_COMMENT TEXT,
  NEGATIVE_COMMENT TEXT,
  REVIEW_DATE      DATE NOT NULL DEFAULT (CURRENT_DATE),
  IS_VERIFIED_STAY BOOLEAN NOT NULL DEFAULT TRUE,
  CLEANLINESS      TINYINT NOT NULL,
  COMFORT          TINYINT NOT NULL,
  LOCATION         TINYINT NOT NULL,
  FACILITIES       TINYINT NOT NULL,
  STAFF            TINYINT NOT NULL,
  VALUE_FOR_MONEY  TINYINT NOT NULL,
  OVERALL_SCORE    DECIMAL(4, 2) GENERATED ALWAYS AS
                   ((CLEANLINESS + COMFORT + LOCATION + FACILITIES + STAFF + VALUE_FOR_MONEY) / 6) STORED,  -- RB07
  BOOKING_ID       INT NOT NULL UNIQUE,                 -- 1:1 với BOOKING
  FOREIGN KEY (BOOKING_ID) REFERENCES BOOKING (BOOKING_ID),
  CONSTRAINT RB05_SCORE_RANGE CHECK (
    CLEANLINESS BETWEEN 1 AND 10 AND COMFORT BETWEEN 1 AND 10 AND LOCATION BETWEEN 1 AND 10 AND
    FACILITIES BETWEEN 1 AND 10 AND STAFF BETWEEN 1 AND 10 AND VALUE_FOR_MONEY BETWEEN 1 AND 10)
);

CREATE TABLE REVIEW_PHOTOS (
  REVIEW_ID INT,
  PHOTO_URL VARCHAR(255),
  PRIMARY KEY (REVIEW_ID, PHOTO_URL),
  FOREIGN KEY (REVIEW_ID) REFERENCES REVIEW (REVIEW_ID) ON DELETE CASCADE
